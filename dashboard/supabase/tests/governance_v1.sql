-- All fixtures and account permission changes are rolled back, including the activity log.
begin;
do $$
declare manager_user uuid; director_user uuid; lead_user uuid; own_home uuid; other_home uuid; report uuid; other_report uuid;
 issue uuid; v integer; failed boolean; body jsonb; snapshot jsonb; test_member_id uuid;
begin
 select m.user_id,a.home_id into manager_user,own_home from public.qa_members m join public.qa_member_homes a on a.member_id=m.id where m.active limit 1;
 select id into director_user from public.profiles where role='director' limit 1;
 select id into lead_user from public.profiles where role='manager' and id<>manager_user limit 1;
 select id into other_home from public.qa_homes where id<>own_home and active limit 1;
 select s.id into report from public.qa_submissions s join public.qa_periods p on p.id=s.period_id where s.home_id=own_home and s.form_version=2 and s.status='draft' and p.closed_at is null order by p.month_start desc limit 1;
 select id into other_report from public.qa_submissions where home_id=other_home and form_version=2 limit 1;
 if manager_user is null or director_user is null or lead_user is null or report is null or other_report is null then raise exception 'Test requires an assigned manager, two homes, director and a second manager';end if;
 update public.workspace_access set qa=true,maintenance=true,visible_sections=array['qa.overview','qa.monthly_reports','qa.audits','qa.incidents','qa.risks','qa.homes','maintenance.issues'] where user_id=manager_user;
 insert into public.workspace_access(user_id,maintenance,can_manage_maintenance,visible_sections) values(lead_user,true,true,array['maintenance.issues'])
 on conflict(user_id) do update set maintenance=true,can_manage_maintenance=true,visible_sections=array['maintenance.issues'];
 perform set_config('request.jwt.claim.sub',manager_user::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',manager_user,'role','authenticated')::text,true);
 execute 'set local role authenticated';
 if exists(select 1 from public.qa_submissions where home_id=other_home) then raise exception 'Cross-home report read allowed';end if;
 failed=false;begin perform public.qa_save_report(other_report,1,'draft','{"answers":{},"occupied_beds":"","records_confirmed":false}');exception when insufficient_privilege then failed=true;end;
 if not failed then raise exception 'Cross-home report save allowed';end if;
 failed=false;begin insert into public.qa_records(kind,home_id,occurred_on,title,status,data) values('maintenance',other_home,current_date,'Rollback fixture','Reported','{"description":"Rollback fixture issue","location":"Kitchen"}');exception when insufficient_privilege then failed=true;end;
 if not failed then raise exception 'Cross-home insert allowed';end if;
 insert into public.qa_records(kind,home_id,occurred_on,title,status,data) values('maintenance',own_home,current_date,'Rollback fixture','Reported','{"description":"Rollback fixture issue","location":"Kitchen","follow_up":""}') returning id into issue;
 update public.qa_records set data=jsonb_set(data,'{follow_up}','"Manager follow-up"'),version=version+1 where id=issue;
 failed=false;begin update public.qa_records set status='Completed',version=version+1 where id=issue;exception when insufficient_privilege then failed=true;end;
 if not failed then raise exception 'Reporter managed maintenance status';end if;
 failed=false;begin update public.qa_records set home_id=other_home,version=version+1 where id=issue;exception when others then failed=true;end;
 if not failed then raise exception 'Record moved to another home';end if;
 select version into v from public.qa_submissions where id=report;
 v=public.qa_save_report(report,v,'draft','{"answers":{},"occupied_beds":"","records_confirmed":false}');
 failed=false;begin perform public.qa_save_report(report,v-1,'draft','{"answers":{}}');exception when serialization_failure then failed=true;end;
 if not failed then raise exception 'Stale version accepted';end if;
 failed=false;begin perform public.qa_save_report(report,v,'submit','{"answers":{},"occupied_beds":"0","records_confirmed":true}');exception when others then failed=true;end;
 if not failed then raise exception 'Incomplete report submitted';end if;
 select jsonb_build_object('answers',jsonb_object_agg(q->>'code',jsonb_build_object('answer','yes','note','')),'occupied_beds','0','records_confirmed',true) into body
 from public.qa_questionnaires c cross join lateral jsonb_array_elements(c.questions) q
 where c.version=2 and (jsonb_array_length(q->'provisions')=0 or q->'provisions' ? (select provision from public.qa_homes where id=own_home));
 v=public.qa_save_report(report,v,'submit',body);
 snapshot=public.qa_visible_report(report)->'snapshot';
 if snapshot is null then raise exception 'Snapshot missing';end if;
 failed=false;begin perform public.qa_save_report(report,v,'draft',body);exception when others then failed=true;end;
 if not failed then raise exception 'Submitted report remained editable';end if;
 failed=false;begin perform public.qa_save_report(report,v,'approve');exception when insufficient_privilege then failed=true;end;
 if not failed then raise exception 'Manager approved own report';end if;
 execute 'reset role';
 perform set_config('request.jwt.claim.sub',lead_user::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',lead_user,'role','authenticated')::text,true);
 execute 'set local role authenticated';
 update public.qa_records set status='Completed',version=version+1 where id=issue;
 if not found then raise exception 'Maintenance lead could not manage another home';end if;
 execute 'reset role';
 perform set_config('request.jwt.claim.sub',director_user::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',director_user,'role','authenticated')::text,true);
 execute 'set local role authenticated';
 v=public.qa_save_report(report,v,'approve');
 if (public.qa_visible_report(report)->'snapshot') is distinct from snapshot then raise exception 'Snapshot changed after a register update';end if;
 v=public.qa_save_report(report,v,'reopen','{}','Please review the report');
 execute 'reset role';
 perform set_config('request.jwt.claim.sub',manager_user::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',manager_user,'role','authenticated')::text,true);
 execute 'set local role authenticated';
 v=public.qa_save_report(report,v,'draft',body);
 execute 'reset role';
 update public.qa_members set active=false where user_id=manager_user;
 execute 'set local role authenticated';
 if exists(select 1 from public.qa_submissions where id=report) then raise exception 'Inactive manager retained access';end if;
 failed=false;begin perform public.qa_save_report(report,v,'draft',body);exception when insufficient_privilege then failed=true;end;
 if not failed then raise exception 'Revoked assignment allowed a save';end if;
 execute 'reset role';
 -- The assignment RPC handles multiple homes and an empty list atomically.
 perform set_config('request.jwt.claim.sub',director_user::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',director_user,'role','authenticated')::text,true);
 execute 'set local role authenticated';
 perform public.qa_assign_homes(manager_user,true,array[own_home,other_home]);
 failed=false;begin perform public.qa_assign_homes(manager_user,true,array[gen_random_uuid()]);exception when others then failed=true;end;
 if not failed then raise exception 'Unknown home accepted';end if;
 execute 'reset role';
 select id into test_member_id from public.qa_members where user_id=manager_user;
 if (select count(*) from public.qa_member_homes where qa_member_homes.member_id=test_member_id)<>2 then raise exception 'Failed assignment changed the saved list';end if;
 perform set_config('request.jwt.claim.sub',manager_user::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',manager_user,'role','authenticated')::text,true);
 execute 'set local role authenticated';
 if not exists(select 1 from public.qa_submissions where id=other_report) then raise exception 'Second assigned home is not accessible';end if;
 execute 'reset role';
 perform set_config('request.jwt.claim.sub',director_user::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',director_user,'role','authenticated')::text,true);
 execute 'set local role authenticated';
 perform public.qa_assign_homes(manager_user,true,array[]::uuid[]);
 execute 'reset role';
 perform set_config('request.jwt.claim.sub',manager_user::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',manager_user,'role','authenticated')::text,true);
 execute 'set local role authenticated';
 if exists(select 1 from public.qa_submissions) then raise exception 'Manager with no homes can see reports';end if;
 execute 'reset role';
end $$;
rollback;
select 'governance permission and report lifecycle assertions passed; all test changes rolled back' as result;
